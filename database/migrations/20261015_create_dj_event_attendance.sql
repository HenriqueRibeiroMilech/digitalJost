SET XACT_ABORT ON;

BEGIN TRANSACTION;

CREATE TABLE dbo.DJ_EVENT_ATTENDANCE_LISTS (
    id INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_DJ_EVENT_ATTENDANCE_LISTS PRIMARY KEY,
    event_id INT NOT NULL,
    name NVARCHAR(120) NOT NULL,
    created_by NVARCHAR(128) NOT NULL,
    created_at DATETIME2(3) NOT NULL
        CONSTRAINT DF_DJ_EVENT_ATTENDANCE_LISTS_created_at DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DJ_EVENT_ATTENDANCE_LISTS_event FOREIGN KEY (event_id)
        REFERENCES dbo.DJ_EVENTS (id) ON DELETE CASCADE
);

CREATE INDEX IX_DJ_EVENT_ATTENDANCE_LISTS_event
    ON dbo.DJ_EVENT_ATTENDANCE_LISTS (event_id, id DESC);

CREATE TABLE dbo.DJ_EVENT_ATTENDANCE_ENTRIES (
    id INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_DJ_EVENT_ATTENDANCE_ENTRIES PRIMARY KEY,
    list_id INT NOT NULL,
    registration VARCHAR(12) NOT NULL,
    name NVARCHAR(200) NULL,
    department NVARCHAR(200) NULL,
    created_by NVARCHAR(128) NOT NULL,
    created_at DATETIME2(3) NOT NULL
        CONSTRAINT DF_DJ_EVENT_ATTENDANCE_ENTRIES_created_at DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DJ_EVENT_ATTENDANCE_ENTRIES_list FOREIGN KEY (list_id)
        REFERENCES dbo.DJ_EVENT_ATTENDANCE_LISTS (id) ON DELETE CASCADE,
    CONSTRAINT UQ_DJ_EVENT_ATTENDANCE_ENTRIES_registration UNIQUE (list_id, registration),
    CONSTRAINT CK_DJ_EVENT_ATTENDANCE_ENTRIES_registration CHECK (
        DATALENGTH(registration) = 12
        AND LEN(registration) = 12
        AND registration COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^0-9]%'
    )
);

CREATE INDEX IX_DJ_EVENT_ATTENDANCE_ENTRIES_list
    ON dbo.DJ_EVENT_ATTENDANCE_ENTRIES (list_id, id DESC);

COMMIT TRANSACTION;
